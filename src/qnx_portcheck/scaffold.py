def plan_scaffold(root: Path, name: str | None = None, out: Path | None = None,
                  build_system: str | None = None) -> list[PlannedFile]:
    root = Path(root).resolve()
    detection = Detection(build_system, "--build-system override") if build_system else detect_build_system(root)
    if detection.system not in {"cmake", "meson", "autotools", "make"}:
        raise ScaffoldError(f"unsupported build system: {detection.system}")
    cleanname = re.sub(r"[^A-Za-z0-9_+-]", "_", name if name is not None else root.name)
    outdir = Path(out).resolve() if out is not None else root / "qnx" / "build"
    common, extra = _common(detection.system, cleanname, (root / "configure").is_file())
    sources = {"cmake":"ports/cJSON/common.mk", "meson":"ports/fribidi/common.mk", "autotools":"ports/libffi/common.mk", "make":"ports/bzip2/common.mk"}
    specs = [("Makefile", "ports/cJSON/Makefile", "LIST=OS\nifndef QRECURSE\nQRECURSE=recurse.mk\nifdef QCONFIG\nQRDIR=$(dir $(QCONFIG))\nendif\nendif\ninclude $(QRDIR)$(QRECURSE)\n"),
             ("common.mk", sources[detection.system], common),
             ("nto-aarch64-le/Makefile", "ports/cJSON/nto-aarch64-le/Makefile", "include ../common.mk\n"),
             ("nto-x86_64-o/Makefile", "ports/cJSON/nto-x86_64-o/Makefile", "include ../common.mk\n")]
    if detection.system == "cmake": specs.append(("qnx.nto.toolchain.cmake", "ports/cJSON/qnx.nto.toolchain.cmake", extra))
    if detection.system == "meson": specs.append(("qnx_cross.txt.in", "ports/fribidi/qnx_cross.txt.in", extra))
    return [PlannedFile(outdir / rel, provenance_header(source, detection) + body, source) for rel, source, body in specs]

def write_scaffold(planned: Sequence[PlannedFile], force: bool = False, dry_run: bool = False) -> list[Result]:
    results = []
    for item in planned:
        exists = item.path.exists()
        if dry_run:
            status = "would skip" if exists and not force else ("would overwrite" if exists else "would create")
        elif exists and not force:
            status = "skipped (exists)"
        else:
            item.path.parent.mkdir(parents=True, exist_ok=True)
            item.path.write_text(item.content, encoding="utf-8")
            status = "overwrote" if exists else "created"
        results.append(Result(item.path, status))
    return results

def run(args: argparse.Namespace) -> int:
    try:
        planned = plan_scaffold(Path(args.path), args.name, Path(args.out) if args.out else None, args.build_system)
        for result in write_scaffold(planned, args.force, args.dry_run):
            print(f"{result.status}: {result.path}")
        print('Hint: QNX_PROJECT_ROOT="$(pwd)" make -C qnx/build install (requires a QNX SDP environment; not executed by this tool).')
        return 0
    except ScaffoldError as exc:
        print(str(exc), file=sys.stderr)
        return 2

def register(subparsers: argparse._SubParsersAction) -> None:
    parser = subparsers.add_parser("scaffold", help="generate draft QNX build scaffolding")
    parser.add_argument("path")
    parser.add_argument("--name")
    parser.add_argument("--out")
    parser.add_argument("--build-system", choices=("cmake", "meson", "autotools", "make"))
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    parser.set_defaults(func=run)

def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="qnx-portcheck")
    register(parser.add_subparsers(dest="command", required=True))
    args = parser.parse_args(argv)
    return args.func(args)

if __name__ == "__main__":
    raise SystemExit(main())
