"""Generate draft QNX recursive-make scaffolding."""
from __future__ import annotations
import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence
from qnx_portcheck import __version__

UPSTREAM_REPO = "https://github.com/qnx-ports/build-files"
UPSTREAM_SHA = "79d94bd6f1d66e524b17c1f26379ac0ef9bd24c5"

class ScaffoldError(Exception):
    pass

@dataclass(frozen=True)
class Detection:
    system: str
    evidence: str

@dataclass(frozen=True)
class PlannedFile:
    path: Path
    content: str
    source_path: str

@dataclass(frozen=True)
class Result:
    path: Path
    status: str

def detect_build_system(root: Path) -> Detection:
    root = Path(root)
    for filename, system in (("CMakeLists.txt", "cmake"), ("meson.build", "meson"),
                             ("configure.ac", "autotools"), ("configure.in", "autotools")):
        if (root / filename).is_file():
            return Detection(system, filename)
    conf = root / "configure"
    if conf.is_file():
        return Detection("autotools", "configure")
    for filename in ("GNUmakefile", "Makefile", "makefile"):
        if (root / filename).is_file():
            return Detection("make", filename)
    raise ScaffoldError(f"cannot detect build system in project root: {root}")

def provenance_header(source_path: str, detection: Detection) -> str:
    return (f"# Generated by qnx-portcheck scaffold {__version__} -- DRAFT, review before use.\n"
            "# Not built or run on a QNX target by qnx-portcheck.\n"
            f"# Pattern source: {UPSTREAM_REPO} @ {UPSTREAM_SHA}\n"
            f"#   path: {source_path}\n"
            f"# Detected build system: {detection.system} (evidence: {detection.evidence})\n")

