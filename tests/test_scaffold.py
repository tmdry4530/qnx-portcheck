import argparse
from pathlib import Path

import pytest

from qnx_portcheck.scaffold import (ScaffoldError, detect_build_system, plan_scaffold,
                                    register, run, write_scaffold, UPSTREAM_SHA, UPSTREAM_REPO)

@pytest.mark.parametrize("file,system", [("CMakeLists.txt", "cmake"), ("meson.build", "meson"),
                                         ("configure.ac", "autotools"), ("configure", "autotools"),
                                         ("Makefile", "make")])
def test_detection(tmp_path, file, system):
    (tmp_path / file).touch()
    assert detect_build_system(tmp_path).system == system

def test_priority_and_qnx_ignored(tmp_path):
    (tmp_path / "CMakeLists.txt").touch()
    (tmp_path / "Makefile").touch()
    assert detect_build_system(tmp_path).system == "cmake"
    other = tmp_path / "other"
    other.mkdir()
    (other / "qnx").mkdir()
    (other / "qnx" / "Makefile").touch()
    with pytest.raises(ScaffoldError):
        detect_build_system(other)

def test_unknown(tmp_path):
    with pytest.raises(ScaffoldError):
        detect_build_system(tmp_path)

@pytest.mark.parametrize("system,extra", [("cmake", "qnx.nto.toolchain.cmake"),
                                            ("meson", "qnx_cross.txt.in"),
                                            ("autotools", None), ("make", None)])
def test_generated_sets_and_provenance(tmp_path, system, extra):
    root = tmp_path / "demo"
    root.mkdir()
    (root / {"cmake":"CMakeLists.txt", "meson":"meson.build", "autotools":"configure.ac", "make":"Makefile"}[system]).touch()
    files = plan_scaffold(root)
    names = {f.path.relative_to(root / "qnx" / "build").as_posix() for f in files}
    assert "nto-aarch64-le/Makefile" in names and "nto-x86_64-o/Makefile" in names
    assert (extra in names) if extra else ("qnx.nto.toolchain.cmake" not in names and "qnx_cross.txt.in" not in names)
    for f in files:
        assert f.content.startswith("# Generated by")
        assert UPSTREAM_REPO in f.content and UPSTREAM_SHA in f.content
        assert f"path: {f.source_path}" in f.content
        if f.path.name == "Makefile" and f.path.parent.name.startswith("nto-"):
            assert f.content.endswith("include ../common.mk\n")
        ref = Path("/workspace/qnxref/build-files") / f.source_path
        if Path("/workspace/qnxref/build-files").is_dir():
            assert ref.is_file()

def test_name_and_out(tmp_path):
    root = tmp_path / "a project!"
    root.mkdir()
    (root / "Makefile").touch()
    files = plan_scaffold(root)
    assert "NAME=a_project_" in next(f.content for f in files if f.path.name == "common.mk")
    assert "NAME=chosen-name" in next(f.content for f in plan_scaffold(root, name="chosen-name") if f.path.name == "common.mk")
    out = tmp_path / "elsewhere"
    assert all(f.path.is_relative_to(out) for f in plan_scaffold(root, out=out))

def test_write_modes(tmp_path):
    root = tmp_path / "p"
    root.mkdir()
    (root / "Makefile").touch()
    planned = plan_scaffold(root)
    assert all(not f.path.exists() for f in planned)
    write_scaffold(planned, dry_run=True)
    assert all(not f.path.exists() for f in planned)
    write_scaffold(planned)
    target = planned[0].path
    target.write_text("keep")
    assert write_scaffold(planned)[0].status == "skipped (exists)"
    assert target.read_text() == "keep"
    write_scaffold(planned, force=True)
    assert target.read_text() == planned[0].content

def test_autotools_autoreconf_decided_at_generation(tmp_path):
    (tmp_path / "configure.ac").touch()
    assert "autoreconf -fi" in next(f.content for f in plan_scaffold(tmp_path) if f.path.name == "common.mk")
    (tmp_path / "configure").touch()
    assert "autoreconf -fi" not in next(f.content for f in plan_scaffold(tmp_path) if f.path.name == "common.mk")

def test_register_run_and_unknown(tmp_path, capsys):
    (tmp_path / "Makefile").touch()
    parser = argparse.ArgumentParser()
    subs = parser.add_subparsers()
    register(subs)
    args = parser.parse_args(["scaffold", str(tmp_path), "--dry-run"])
    assert run(args) == 0
    empty = tmp_path / "empty"
    empty.mkdir()
    assert run(argparse.Namespace(path=str(empty), name=None, out=None, build_system=None,
                                  force=False, dry_run=False)) == 2

def test_source_paths_documented(tmp_path):
    (tmp_path / "CMakeLists.txt").touch()
    doc = Path(__file__).parents[1] / "docs" / "scaffold-sources.md"
    text = doc.read_text()
    for item in plan_scaffold(tmp_path):
        assert UPSTREAM_SHA in text and item.source_path in text
